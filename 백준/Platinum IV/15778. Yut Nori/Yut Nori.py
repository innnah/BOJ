n = int(input())
mals = [-2 for _ in range(8)]
for _ in range(n):
    mal, yut = input().rstrip().split()
    mal = mal_no[mal]
    yut = d_idx[yut.count('F')]
    if mals[mal] == -2: mals[mal] = 0
    tmp = [mal]
    for i in range(0+(mal>3)*4, 4+(mal>3)*4):
        if mal == i: continue
        if mals[i] == mals[mal]:
            tmp.append(i)
    ne = moves[mals[mal]][yut]
    for i in range(0+(mal<4)*4, 4+(mal<4)*4):
        if mals[i] == ne:
            mals[i] = -2
    for i in tmp:
        mals[i] = ne

