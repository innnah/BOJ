l = [223092870, 9699690, 510510, 30030, 2310, 210, 30, 6, 2, 1]
d = {223092870:"*2*3*5*7*11*13*17*19*23", 9699690:"*2*3*5*7*11*13*17*19", 510510:"*2*3*5*7*11*13*17", \
    30030:"*2*3*5*7*11*13", 2310:"*2*3*5*7*11", 210:"*2*3*5*7", 30:"*2*3*5", 6:"*2*3", 2:"*2", 1:""}
while True:
    n = int(input())
    if n == 0:
        break
    print(f"{n} = ", end = '')
    l2 = []
    for i in l:
        if n >= i:
            l2.append([n//i, i])
            n %= i
    l2 = list(reversed(l2))
    for a in l2[:-1]:
        print(f"{a[0]}{d[a[1]]} + ", end = '')
    print(f"{l2[-1][0]}{d[l2[-1][1]]}")