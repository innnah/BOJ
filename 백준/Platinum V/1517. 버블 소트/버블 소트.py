import sys as 시스템
입력 = 시스템.stdin.readline
정수 = int
정렬된 = sorted
범위 = range
목록 = list
출력 = print
자료구조_함수_씌우기 = map

def 질의(위치):
    결과 = 0
    while 위치 > 0:
        결과 += 나무[위치]
        위치 -= (위치 & -위치)
    return 결과
def 갱신(위치, 숫자):
    while 위치 <= 개수:
        나무[위치] += 숫자
        위치 += (위치 & -위치)
개수 = 정수(입력())
수열 = 목록(자료구조_함수_씌우기(정수, 입력().split()))
정렬된_수열 = 목록(정렬된(수열))
사전 = {정렬된_수열[i-1] : i for i in 범위(1, 개수+1)}
압축된_수열 = [사전[숫자] for 숫자 in 수열]
나무 = [0 for _ in 범위(개수+1)]
결과 = 0
for 위치 in 범위(개수):
    갱신(압축된_수열[위치], 1)
    결과 += 질의(개수) - 질의(압축된_수열[위치])
출력(결과)